-- EPGStation 互換の API (#431) で使う、録画の整数の ID。
ALTER TABLE "recordings" ADD COLUMN "api_id" bigint;
-- EPGStation から取り込んだ録画は、取り込み元の ID を引き継ぐ。同じ ID を複数の取り込み元から取り込んでいたら、先に取り込んだものに譲る。
UPDATE "recordings" r SET "api_id" = s.source_id
FROM (
  SELECT DISTINCT ON (source_id) source_id, target_id FROM "import_sources"
  WHERE kind = 'recorded' ORDER BY source_id, created_at, source
) s
WHERE s.target_id = r.id;
-- ほかの録画には、取り込んだ録画の ID の後ろから、録画を始めた順に振る。
UPDATE "recordings" r SET "api_id" = n.base + n.rn
FROM (
  SELECT id, row_number() OVER (ORDER BY recorded_from, id) AS rn,
    (SELECT coalesce(max("api_id"), 0) FROM "recordings") AS base
  FROM "recordings" WHERE "api_id" IS NULL
) n
WHERE r.id = n.id;
-- modify "recordings" table
ALTER TABLE "recordings" ALTER COLUMN "api_id" SET NOT NULL, ALTER COLUMN "api_id" ADD GENERATED BY DEFAULT AS IDENTITY, ADD CONSTRAINT "recordings_api_id_key" UNIQUE ("api_id");
-- これから作る録画は、振った ID の後ろから振る。
SELECT setval(pg_get_serial_sequence('recordings', 'api_id'), coalesce((SELECT max("api_id") FROM "recordings"), 0) + 1, false);

