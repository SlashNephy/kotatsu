// printenclosed は、囲み文字の表 (epg.EnclosedCharacters) を TypeScript にして標準出力に書く。
// 番組名から囲み文字を外して描く画面と、条件で囲み文字を選ぶ画面が、バックエンドと同じ表を使うよう、
// mise run generate で web/src/futon/enclosedCharacters.gen.ts に書き出す。
package main

import (
	"bufio"
	"fmt"
	"os"

	"github.com/SlashNephy/kotatsu/internal/epg"
)

func main() {
	w := bufio.NewWriter(os.Stdout)
	write := func(format string, args ...any) {
		if _, err := fmt.Fprintf(w, format, args...); err != nil {
			panic(err)
		}
	}

	write("// Code generated by internal/epg/printenclosed. DO NOT EDIT.\n")
	write("// 番組名に付く ARIB の囲み文字の表 (設計書 4.2)。internal/epg/enclosed.go から作る。\n\n")
	write("export type EnclosedGroup = '%s' | '%s';\n\n", epg.EnclosedGroupIdeographic, epg.EnclosedGroupAlphanumeric)
	write("export type EnclosedCharacter = {\n")
	write("  readonly character: string;\n")
	write("  readonly label: string;\n")
	write("  readonly group: EnclosedGroup;\n")
	write("};\n\n")
	write("export const enclosedCharacters: readonly EnclosedCharacter[] = [\n")
	for _, c := range epg.EnclosedCharacters() {
		write("  { character: '\\u{%X}', label: '%s', group: '%s' },\n", c.Character, c.Label, c.Group)
	}
	write("];\n")

	if err := w.Flush(); err != nil {
		panic(err)
	}
}
