// printschema は、GraphQL のスキーマを 1 つの SDL にまとめて標準出力に書く。
// graph/schema/*.graphqls は extend type で分けて書いているが、Relay のコンパイラは 1 つのファイルを読むので、
// mise run //backend:generate で frontend/schema.graphql に書き出す。
package main

import (
	"fmt"
	"os"

	"github.com/vektah/gqlparser/v2/formatter"

	"github.com/SlashNephy/kotatsu/internal/web/graph/generated"
)

func main() {
	var config generated.Config
	schema := generated.NewExecutableSchema(config).Schema()
	if _, err := fmt.Fprintln(os.Stdout, "# Code generated by internal/web/graph/printschema. DO NOT EDIT."); err != nil {
		panic(err)
	}
	formatter.NewFormatter(os.Stdout, formatter.WithIndent("  ")).FormatSchema(schema)
}
